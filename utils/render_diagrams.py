#!/usr/bin/env python3
"""render_diagrams.py — every diagram of the documentation is a file, and its picture is drawn from it.

    python3 utils/render_diagrams.py            # draw what is missing or stale
    python3 utils/render_diagrams.py --all      # draw every diagram again
    python3 utils/render_diagrams.py --check    # write nothing; exit 1 where a rule below is broken
    python3 utils/render_diagrams.py --list     # every source, its picture's state and the pages that show it
    python3 utils/render_diagrams.py docs/ein/user/02-guide     # only the diagrams under a path

A page of `docs/` shows a diagram as an image, `![what it shows](diagrams/NN-name.svg)`, and never as a fenced
block: a block is drawn by whatever reads the page, and not every reader draws one. The diagram's source is a file
in the `diagrams/` folder beside the page, `NN-name.dot` (Graphviz) or `NN-name.puml` (PlantUML), and the picture,
`NN-name.svg`, is drawn from it here and never edited (Q-M1f.368).

**The stamp.** Graphviz's output differs from one version to the next, so a picture cannot be checked by drawing it
again and comparing. Each picture instead ends with one line, an XML comment after the closing `</svg>`, that
carries the SHA-256 of the source's bytes:

    <!-- source sha256: 9f2c…e1 -->

A picture is *fresh* when that hash is its source's. `--check` reads the stamps and runs neither Graphviz nor
PlantUML, so it holds wherever the tree is checked out.

**What `--check` holds**, each finding one line, `path: what`:

1. a source (`.dot`, `.puml`) has its picture beside it, and a picture its source;
2. a picture's stamp is its source's hash: a source edited and not drawn again fails;
3. a picture PlantUML drew as an error (the words *Syntax error* in it) fails;
4. a `diagrams/` folder holds nothing else: no other kind of file, no folder, no stem with two sources;
5. the name: `NN-name`, letters, digits, `-` and `.`; `NN` is the number of the page that shows it, a page of the
   folder the `diagrams/` folder is in (`00` for that folder's `README.md`), and that page shows it;
6. every picture is shown by a page, and every `diagrams/*.svg` a page shows exists;
7. no picture carries a path of the machine it was drawn on.

**Drawing.** `dot -Tsvg` for a `.dot` (a graph that names its `layout` is laid out by it), `plantuml -tsvg
-nometadata -pipe` for a `.puml`, as many at once as the machine has threads. Graphviz's comment naming its
version is dropped, since some builds write their build date there, and PlantUML's copy of the source is not
written (`-nometadata`). A source its tool refuses, or one PlantUML draws as an error, leaves no picture: the old
one is removed, the run exits 1, and `--check` then fails on the source with no picture.

Rule 1 of `check_doc_blocks.py`, a gate step, is this script's `--check` and Graphviz laying out every `.dot`.
The standard library's rule drawings (`gen_stdlib_rule_pages.py`) and the grammar's diagrams (the test
`ein-ir/tests/grammar_pages.rs`) write sources only; their pictures are drawn here.
"""
from __future__ import annotations

import argparse
import hashlib
import os
import re
import shutil
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
DOCS = "docs"
FOLDER = "diagrams"
SOURCES = {".dot": "dot", ".puml": "plantuml"}
PICTURE = ".svg"

STAMP = re.compile(r"\n<!-- source sha256: ([0-9a-f]{64}) -->\n?\Z")
STEM = re.compile(r"(\d\d)-[A-Za-z0-9]+(?:[.-][A-Za-z0-9]+)*")
PAGE = re.compile(r"(\d\d)-.*\.md")
IMAGE = re.compile(r"!\[([^\]]*)\]\(([^)\s]+)(?:\s+\"[^\"]*\")?\)")
#: What PlantUML writes into the drawing of a source it could not read.
PLANTUML_ERROR = re.compile(r"Syntax [Ee]rror[?!]")
#: A path of the machine a picture was drawn on.
LOCAL_PATH = re.compile(r"(?:/home/|/tmp/|/Users/|file://)[\w./-]+")
GRAPHVIZ_COMMENT = re.compile(r"<!-- Generated by graphviz version [^>]*-->\n")


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def stamp_of(picture: Path) -> str | None:
    """The hash a picture is stamped with, or None."""
    try:
        with picture.open("rb") as f:
            f.seek(0, os.SEEK_END)
            f.seek(max(0, f.tell() - 200))
            tail = f.read().decode("utf-8", "replace")
    except OSError:
        return None
    m = STAMP.search(tail)
    return m.group(1) if m else None


def folders(root: Path) -> list[Path]:
    """Every `diagrams/` folder under `root`, in order."""
    out = []
    for here, dirs, _files in os.walk(root):
        dirs.sort()
        if FOLDER in dirs:
            out.append(Path(here) / FOLDER)
            dirs.remove(FOLDER)
    return out


def sources(root: Path) -> list[Path]:
    return [p for d in folders(root) for p in sorted(d.iterdir())
            if p.is_file() and p.suffix in SOURCES]


def rel(p: Path) -> str:
    return str(p.relative_to(REPO))


def shown(root: Path) -> dict[Path, list[tuple[Path, int, str]]]:
    """Each picture a page under `root` shows → the (page, line, alt text) that show it. A picture is
    an image whose target is a `.svg` in a `diagrams/` folder."""
    out: dict[Path, list[tuple[Path, int, str]]] = {}
    for here, dirs, files in os.walk(root):
        dirs.sort()
        if FOLDER in dirs:
            dirs.remove(FOLDER)
        for name in sorted(files):
            if not name.endswith(".md"):
                continue
            page = Path(here) / name
            for n, line in enumerate(page.read_text(encoding="utf-8").split("\n"), start=1):
                for m in IMAGE.finditer(line):
                    target = m.group(2).split("#")[0]
                    if re.match(r"[a-z][a-z0-9+.-]*:", target) or not target.endswith(PICTURE):
                        continue
                    res = Path(os.path.normpath(page.parent / target))
                    if res.parent.name == FOLDER:
                        out.setdefault(res, []).append((page, n, m.group(1)))
    return out


# ── drawing ─────────────────────────────────────────────────────────────────


def draw(source: Path) -> str | None:
    """Draw `source` into the picture beside it, stamped. Answers what went wrong, or None."""
    picture = source.with_suffix(PICTURE)
    tool = SOURCES[source.suffix]
    data = source.read_bytes()
    cmd = ["dot", "-Tsvg"] if tool == "dot" else ["plantuml", "-tsvg", "-nometadata", "-pipe"]
    p = subprocess.run(cmd, input=data, capture_output=True)
    out = p.stdout.decode("utf-8", "replace")
    err = p.stderr.decode("utf-8", "replace").strip()
    first = next((l.strip() for l in err.splitlines() if l.strip()), "")
    what = None
    if p.returncode != 0 or "<svg" not in out:
        what = f"`{tool}` draws nothing (exit {p.returncode})" + (f": {first[:200]}" if first else "")
    elif tool == "plantuml" and PLANTUML_ERROR.search(out):
        what = "PlantUML draws it as a syntax error"
    if what:
        picture.unlink(missing_ok=True)
        return what
    out = GRAPHVIZ_COMMENT.sub("", out, count=1)
    out = out.rstrip("\n") + f"\n<!-- source sha256: {hashlib.sha256(data).hexdigest()} -->\n"
    picture.write_text(out, encoding="utf-8")
    return None


def render(todo: list[Path]) -> list[tuple[Path, str]]:
    with ThreadPoolExecutor(max_workers=os.cpu_count() or 1) as pool:
        return [(s, what) for s, what in zip(todo, pool.map(draw, todo)) if what]


# ── the check ───────────────────────────────────────────────────────────────

Finding = tuple[str, str]  # (path, what)


def check(root: Path | None = None) -> list[Finding]:
    """Everything `--check` holds, over the `diagrams/` folders under `root` (default `docs/`)."""
    docs = REPO / DOCS
    root = root or docs
    out: list[Finding] = []
    shows = shown(docs)
    seen: set[Path] = set()
    for folder in folders(root):
        stems: dict[str, list[Path]] = {}
        for p in sorted(folder.iterdir()):
            if p.is_dir() or p.suffix not in (*SOURCES, PICTURE):
                out.append((rel(p), "a `diagrams/` folder holds sources (`.dot`, `.puml`) and their "
                            "pictures (`.svg`), and nothing else"))
                continue
            stems.setdefault(p.stem, []).append(p)
        for stem, files in sorted(stems.items()):
            srcs = [p for p in files if p.suffix in SOURCES]
            pic = folder / (stem + PICTURE)
            seen.add(pic)
            if len(srcs) > 1:
                out.append((rel(srcs[0]), "two sources of one name: " + ", ".join(p.name for p in srcs)))
                continue
            if not srcs:
                out.append((rel(pic), "a picture with no source beside it"))
                continue
            src = srcs[0]
            if not pic.is_file():
                out.append((rel(src), "no picture: `python3 utils/render_diagrams.py` draws it"))
            else:
                stamp = stamp_of(pic)
                text = pic.read_text(encoding="utf-8", errors="replace")
                if stamp is None:
                    out.append((rel(pic), "no stamp of its source's hash: it was not drawn by "
                                "`utils/render_diagrams.py`"))
                elif stamp != sha(src):
                    out.append((rel(pic), f"stale: `{src.name}` changed after it was drawn; "
                                "`python3 utils/render_diagrams.py` draws it again"))
                if src.suffix == ".puml" and PLANTUML_ERROR.search(text):
                    out.append((rel(pic), "PlantUML's drawing of a syntax error"))
                if m := LOCAL_PATH.search(text):
                    out.append((rel(pic), f"a path of the machine it was drawn on: `{m.group(0)}`"))
            # The name, and the page it belongs to.
            m = STEM.fullmatch(stem)
            pages = shows.get(pic, [])
            if not m:
                out.append((rel(src), "its name is not `NN-name` (letters, digits, `-` and `.`)"))
            elif not pages:
                out.append((rel(src), "no page shows its picture"))
            else:
                home = folder.parent
                owners = [pg for pg, _n, _alt in pages if pg.parent == home and (
                    (pg.name == "README.md" and m.group(1) == "00")
                    or ((n := PAGE.fullmatch(pg.name)) is not None and n.group(1) == m.group(1)))]
                if not owners:
                    out.append((rel(src), f"its number is {m.group(1)}, and no page of that number in "
                                f"`{rel(home)}/` shows it (it is shown by "
                                + ", ".join(sorted({rel(pg) for pg, _n, _a in pages})) + ")"))
    # A page that shows a picture no folder has.
    for pic, pages in sorted(shows.items()):
        if pic in seen or not pic.is_relative_to(root):
            continue
        for page, n, _alt in pages:
            out.append((f"{rel(page)}:{n}", f"shows `{rel(pic)}`, which does not exist"))
    return sorted(out)


# ── main ────────────────────────────────────────────────────────────────────


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="write nothing; exit 1 on a finding")
    ap.add_argument("--all", action="store_true", help="draw every diagram, fresh or not")
    ap.add_argument("--list", action="store_true",
                    help="every source: fresh, stale or missing, and the pages that show it")
    ap.add_argument("paths", nargs="*", metavar="PATH",
                    help="only the diagrams under each PATH (default: `docs/`)")
    args = ap.parse_args()

    roots = [Path(os.path.abspath(p)) for p in args.paths] or [REPO / DOCS]
    for r in roots:
        if not r.is_dir() or not r.is_relative_to(REPO / DOCS):
            print(f"render_diagrams: `{r}` is not a folder under `{DOCS}/`", file=sys.stderr)
            return 2

    if args.check:
        found = [f for r in roots for f in check(r)]
        for path, what in found:
            print(f"render_diagrams: {path}: {what}", file=sys.stderr)
        if found:
            print(f"render_diagrams: {len(found)} finding(s)", file=sys.stderr)
            return 1
        n = sum(len(sources(r)) for r in roots)
        print(f"render_diagrams: {n} diagrams, every picture drawn from its source as it stands "
              "and shown by its page")
        return 0

    srcs = [s for r in roots for s in sources(r)]

    def state(s: Path) -> str:
        pic = s.with_suffix(PICTURE)
        if not pic.is_file():
            return "missing"
        return "fresh" if stamp_of(pic) == sha(s) else "stale"

    if args.list:
        shows = shown(REPO / DOCS)
        for s in srcs:
            pages = sorted({rel(pg) for pg, _n, _a in shows.get(s.with_suffix(PICTURE), [])})
            print(f"{state(s):7} {rel(s)}  ← {', '.join(pages) or '(no page)'}")
        return 0

    todo = srcs if args.all else [s for s in srcs if state(s) != "fresh"]
    for tool in sorted({SOURCES[s.suffix] for s in todo}):
        if shutil.which(tool) is None:
            print(f"render_diagrams: no `{tool}` on PATH, and {sum(SOURCES[s.suffix] == tool for s in todo)} "
                  "diagram(s) need it", file=sys.stderr)
            return 127
    failed = render(todo)
    for s, what in failed:
        print(f"render_diagrams: {rel(s)}: {what}", file=sys.stderr)
    print(f"render_diagrams: {len(srcs)} diagrams, {len(todo) - len(failed)} drawn"
          + (f", {len(failed)} FAILED" if failed else ""))
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
