#!/usr/bin/env python3
"""Write the generated parts of `std.bool`: the table of the sixteen functions, and the programs that hold the rules to the columns.

M1f P1f.6, S1f.6.17 (the build, as ruled 2026-11-12). A Boolean function of
two inputs is its column of four outputs, at a b = 00, 01, 10 and 11, and
there are sixteen. From the sixteen columns and their names this script
writes:

    stdlib/bool/gates.ein                     the lines between its BEGIN GENERATED
                                              and END GENERATED comments: the two
                                              bits, `inv`, `le`, the 64 rows of
                                              `gate2` and each function's
                                              `column-name`; the rest of the file,
                                              the sixteen rules among it, is written
                                              by hand
    tests/stdlib/bool/gates/01_*.ein          the second layout, (And A B OUT): each
                                              of the sixteen relations claimed whole
    tests/stdlib/bool/props/01_*.ein … 07_*   what is known of the sixteen, a family
                                              of relations a program, every relation
                                              claimed whole

**The direction is the rules'.** `std.bool.props` derives every property from
the 64 rows by rules (the user's reply 20 (b)), written by hand in
`stdlib/bool/props.ein`; this script computes the same relations from the
columns, in Python, and writes them as the *expected* facts, the claims of
the programs under `tests/stdlib/bool/`. A claim that names a relation closes
it, so a program holds only if the rules derive every listed fact and no
other. Until the build the direction was the other: the banked prototype
shipped the facts and kept the rules as their check.

Two things hold the files besides `--check`:

- `ein-infer/tests/bool_theory.rs` runs this script's `--check` inside
  `cargo test`, which is how the check is in the gate, and holds every row of
  the table and every fact the rules derive to an enumeration written in
  Rust, from each property's definition: three languages, one answer.
- `ein test tests/` runs the programs, and `utils/stdlib_mutants.py` asks
  whether they notice a defect in a rule.

    python3 utils/gen_gates.py            # write the files
    python3 utils/gen_gates.py --check    # exit 1 if one differs
    python3 utils/gen_gates.py --count    # how many facts each relation holds

After a write, `python3 utils/stdlib_manifest.py --write`: `gates.ein` is part
of the stdlib and is embedded in the binary.

The gate names are the stage file's proposal, which the user's reply 19 left
standing. No dependency beyond the standard library.
"""
from __future__ import annotations

import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
GATES = REPO / "stdlib" / "bool" / "gates.ein"
TESTS = REPO / "tests" / "stdlib" / "bool"

BEGIN = ";; BEGIN GENERATED by utils/gen_gates.py: edit the script, never the rows"
END = ";; END GENERATED"

# column (the outputs at a b = 00 01 10 11) -> the gate's name
NAMES = {"0000": "Zero", "0001": "And", "0010": "Andn", "0011": "Fst", "0100": "Randn", "0101": "Snd",
         "0110": "Xor", "0111": "Or", "1000": "Nor", "1001": "Xnor", "1010": "Nsnd", "1011": "Orn",
         "1100": "Nfst", "1101": "Rorn", "1110": "Nand", "1111": "One"}
COLS = {v: k for k, v in NAMES.items()}
F = list(NAMES.values())
B = (0, 1)


def f(name, a, b):
    return int(COLS[name][2 * a + b])


def named(fn):
    return NAMES["".join(str(fn(a, b)) for a in B for b in B)]


def properties():
    """Every relation `std.bool.props` derives, computed from the columns: {relation: set of tuples}."""
    P = {}
    P["column"] = {(n, *COLS[n]) for n in F}
    P["swap-of"] = {(n, named(lambda a, b: f(n, b, a))) for n in F}
    P["complement-of"] = {(n, named(lambda a, b: 1 - f(n, a, b))) for n in F}
    P["dual-of"] = {(n, named(lambda a, b: 1 - f(n, 1 - a, 1 - b))) for n in F}
    P["left-negated"] = {(n, named(lambda a, b: f(n, 1 - a, b))) for n in F}
    P["right-negated"] = {(n, named(lambda a, b: f(n, a, 1 - b))) for n in F}
    P["commutative"] = {(n,) for n in F if all(f(n, a, b) == f(n, b, a) for a in B for b in B)}
    P["assoc-at"] = {(n, str(a), str(b), str(c)) for n in F for a in B for b in B for c in B
                     if f(n, f(n, a, b), c) == f(n, a, f(n, b, c))}
    P["associative"] = {(n,) for n in F
                        if all(f(n, f(n, a, b), c) == f(n, a, f(n, b, c)) for a in B for b in B for c in B)}
    P["idempotent"] = {(n,) for n in F if all(f(n, a, a) == a for a in B)}
    P["reads-first"] = {(n,) for n in F if any(f(n, 0, b) != f(n, 1, b) for b in B)}
    P["reads-second"] = {(n,) for n in F if any(f(n, a, 0) != f(n, a, 1) for a in B)}
    P["ignores-first"] = {(n,) for n in F} - P["reads-first"]
    P["ignores-second"] = {(n,) for n in F} - P["reads-second"]
    P["right-identity-of"] = {(n, str(e)) for n in F for e in B if all(f(n, a, e) == a for a in B)}
    P["left-identity-of"] = {(n, str(e)) for n in F for e in B if all(f(n, e, a) == a for a in B)}
    P["identity-of"] = P["right-identity-of"] & P["left-identity-of"]
    P["right-absorbing-of"] = {(n, str(e)) for n in F for e in B if all(f(n, a, e) == e for a in B)}
    P["left-absorbing-of"] = {(n, str(e)) for n in F for e in B if all(f(n, e, a) == e for a in B)}
    P["absorbing-of"] = P["right-absorbing-of"] & P["left-absorbing-of"]
    P["preserves-zero"] = {(n,) for n in F if f(n, 0, 0) == 0}
    P["preserves-one"] = {(n,) for n in F if f(n, 1, 1) == 1}
    P["monotone"] = {(n,) for n in F
                     if all(f(n, a, b) <= f(n, c, d) for a in B for b in B for c in B for d in B if a <= c and b <= d)}
    P["affine"] = {(n,) for n in F if sum(int(x) for x in COLS[n]) % 2 == 0}
    P["self-dual"] = {(n,) for n in F if (n, n) in P["dual-of"]}
    allf = {(n,) for n in F}
    P["escapes-zero"] = allf - P["preserves-zero"]
    P["escapes-one"] = allf - P["preserves-one"]
    P["escapes-monotone"] = allf - P["monotone"]
    P["escapes-affine"] = allf - P["affine"]
    P["escapes-self-dual"] = allf - P["self-dual"]
    P["complete-alone"] = (P["escapes-zero"] & P["escapes-one"] & P["escapes-monotone"]
                           & P["escapes-affine"] & P["escapes-self-dual"])
    return P


# The programs under tests/stdlib/bool/props/: (file, title, the rules it activates, what the theory promises,
