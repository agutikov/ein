def wrap(items, width=100, indent=""):
    lines, cur = [], indent
    for it in items:
        if len(cur) + len(it) + 1 > width and cur.strip():
            lines.append(cur.rstrip())
            cur = indent
        cur += it + " "
    if cur.strip():
        lines.append(cur.rstrip())
    return "\n".join(lines)


def comment(text):
    return "\n".join((";;; " + line).rstrip() for line in text.splitlines())


def import_line(module, names):
    head = f"(import {module} :symbols ("
    return wrap(names, 100, " " * len(head)).replace(" " * len(head), head, 1) + "))"


def functions_written(facts):
    """The function names a list of facts writes, in the table's order."""
    seen = {x for t in facts for x in t}
    return [n for n in F if n in seen]


def claim(rel, facts):
    vs = " ".join(f"?{chr(ord('a') + i)}" for i in range(len(next(iter(facts)))))
    return (f"(query :goal ({rel} {vs})\n       :expect (model "
            + wrap([f"({rel} {' '.join(x)})" for x in sorted(facts)], 100, " " * 22).lstrip() + "))")


GENERATED = """\
;;;
;;; GENERATED by `utils/gen_gates.py` from the sixteen functions' columns:
;;; edit the script and run it, never this file. Its `--check` is in the
;;; gate, through `ein-infer/tests/bool_theory.rs`, which also holds every
;;; fact to an enumeration in Rust.
;;;"""

MEANS = """\
;;; ── What the expectation means ─────────────────────────────────────────────
;;;
;;; Each query claims one relation's whole extent, computed in Python from the
;;; columns. A claim that names a relation closes it, so it holds only if the
;;; rules derive every listed fact and no other: that is the negative case of
;;; a library with no refutation rule. Every relation is closed, so there is
;;; no candidate: R is {∅}, root's fixpoint, one saturation."""


def gates_block():
    lines = [BEGIN, "(bit 0) (bit 1)", "(inv 0 1) (inv 1 0)", "(le 0 0) (le 0 1) (le 1 1)"]
    for n in F:
        lines.append(" ".join(f"(gate2 {n} {a} {b} {f(n, a, b)})" for a in B for b in B)
                     + f"   (column-name {n} f{COLS[n]})")
    lines.append(END)
    return "\n".join(lines)


def gates_module(current):
    """`stdlib/bool/gates.ein` with its generated lines re-written and the rest kept."""
    lines = current.splitlines(keepends=True)
    starts = [i for i, l in enumerate(lines) if l.rstrip("\n") == BEGIN]
    ends = [i for i, l in enumerate(lines) if l.rstrip("\n") == END]
    if len(starts) != 1 or len(ends) != 1 or ends[0] < starts[0]:
        raise SystemExit(f"{GATES.relative_to(REPO)}: expected one `{BEGIN}` line and one `{END}` after it")
    return "".join(lines[:starts[0]]) + gates_block() + "\n" + "".join(lines[ends[0] + 1:])


def gates_test():
    rows = {n: [(n, str(a), str(b), str(f(n, a, b))) for a in B for b in B] for n in F}
    head = f""";;; `std.bool.gates` — the second layout: a relation a function, derived from
;;; the table by sixteen rules (the user's reply 19 (c)). M1f S1f.6.17.
{GENERATED}
;;; ── What the module promises ───────────────────────────────────────────────
;;;
;;; `(And A B OUT)` holds exactly where `(gate2 And A B OUT)` does: each of
;;; the sixteen relations, `Zero` to `One`, holds its function's four rows of
;;; the table and no other, one rule each, `Zero-rows` to `One-rows`. A
;;; function's name is the module's, as a relation and as a value of `gate2`,
;;; so this program lists all sixteen.
;;;
{MEANS}
"""
    body = [import_line("std.bool.gates", ["gates"] + F), "", "(solve :expect (region (model)))", ""]
    for n in F:
        vs = "?a ?b ?o"
        body.append(f"(query :goal ({n} {vs})\n       :expect (model "
                    + " ".join(f"({n} {' '.join(r[1:])})" for r in rows[n]) + "))")
    return head + "\n" + "\n".join(body) + "\n"


def props_test(P, title, rules, promise, rels):
    facts = [t for r in rels for t in P[r]]
    counts = ", ".join(f"`{r}` {len(P[r])}" for r in rels)
    head = f""";;; `std.bool.props` — {title}. M1f S1f.6.17.
{GENERATED}
;;; ── What the theory promises ───────────────────────────────────────────────
;;;
{comment(promise)}
;;;
;;; The rules: {", ".join(f"`{r}`" for r in rules)}.
;;;
{MEANS}
;;;
{comment(wrap(("The facts a relation: " + counts + ".").split(" "), 76))}
"""
    imports = [import_line("std.bool.props", ["props"] + rels)]
    fs = functions_written(facts)
    if fs:
        imports.append(import_line("std.bool.gates", fs))
    body = imports + ["", "(solve :expect (region (model)))", ""]
    body += [claim(r, P[r]) for r in rels]
    return head + "\n" + "\n".join(body) + "\n"


def build():
    P = properties()
    claimed = [r for _, _, _, _, rels in FAMILIES for r in rels]
    assert sorted(claimed) == sorted(P), "every relation of std.bool.props is claimed exactly once"
    files = {GATES: gates_module(GATES.read_text()),
             TESTS / "gates" / "01_a_relation_a_function.ein": gates_test()}
    for name, title, rules, promise, rels in FAMILIES:
        files[TESTS / "props" / f"{name}.ein"] = props_test(P, title, rules, promise, rels)
    return files, P


def main(argv):
    files, P = build()
    if "--count" in argv:
        for n in P:
            fs = len({t[0] for t in P[n]})
            print(f"{n:20} {len(P[n]):3} facts, {fs:2} functions")
        pairs = {frozenset(t) for t in P["swap-of"] if t[0] != t[1]}
        print(f"swap-of: {len(pairs)} pairs, {sum(1 for t in P['swap-of'] if t[0] == t[1])} functions their own swap; "
              f"{len(pairs) + sum(1 for t in P['swap-of'] if t[0] == t[1])} up to the order of the inputs")
        return 0
    if "--check" in argv:
        stale = [p for p, text in files.items() if not p.exists() or p.read_text() != text]
        for p in stale:
            print(f"stale: {p.relative_to(REPO)} — run `python3 utils/gen_gates.py`", file=sys.stderr)
        return 1 if stale else 0
    for p, text in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
        print("wrote", p.relative_to(REPO))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
